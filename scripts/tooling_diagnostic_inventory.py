"""Generate/check the exhaustive native diagnostic inventory and test cases."""
import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
PRODUCERS = [
    ("LEX", "eta/core/src/eta/reader/lexer.h", "LexErrorKind", "reader.lexer", "Lexer::next_token/next_raw_item", 2),
    ("PARSE", "eta/core/src/eta/reader/parser.h", "ParseErrorKind", "reader.parser", "Parser::parse_toplevel/parse_datum", 2),
    ("EXPAND", "eta/core/src/eta/reader/expander.h", "Kind", "compiler.expander", "Expander::expand_toplevel", 1),
    ("LINK", "eta/core/src/eta/reader/module_linker.h", "Kind", "compiler.linker", "ModuleLinker::index_modules/link", 1),
    ("UNIFIED", "eta/core/src/eta/diagnostic/diagnostic.h", "DiagnosticCode", "compiler.diagnostic", "DiagnosticEngine::diagnostics", 1),
]


def generate():
    rows = ["# Native tooling diagnostic inventory", "", "Generated by `scripts/tooling_diagnostic_inventory.py`; do not edit the table by hand.", "",
            "The adapter is `eta/cst/diagnostic.{h,cpp}`. All entries retain compiler ownership and severity (typed errors are errors). "
            "Typed messages are compiler-provided or the shared diagnostic converter's kind-specific message. "
            "Unified messages, numeric code and related locations are retained verbatim. Every native kind has a generated adapter test.", "",
            "A source resolver proves file identity and byte bounds. Unresolvable/default spans remain absent; providers may explicitly prove a zero-width BOF location. "
            "Module identity and related import/provider locations remain separate. Unknown enum values retain the numeric kind and message with partial classification; "
            "text-only failures use `compiler.unclassified` (status 1 unless the producer declares operation/internal failure). "
            "Unlocated deduplication includes producer, module and message. No adapter invokes expansion, loading or execution.", "",
            "The reader is available as a non-executing service. Expansion can run user macro transformations, and linking expects expanded module forms; "
            "these are adapter inputs only, not automatically callable tooling services. The semantic analyzer requires expanded forms and runtime/builtin environments. "
            "Unified runtime enum members describe an available diagnostic representation, not permission to execute source for analysis. "
            "Unavailable semantic metadata must be reported as missing analysis coverage in later linter phases.", "",
            "| Native kind | Producer/API | External code | Message/location | Exit class |", "| --- | --- | --- | --- | --- |"]
    fixtures = ["// Generated by scripts/tooling_diagnostic_inventory.py. Each row is exercised by cst_tests.cpp."]
    for prefix, path, enum, namespace, api, default_exit in PRODUCERS:
        source = (ROOT / path).read_text(encoding="utf-8")
        body = re.search(r"enum class " + enum + r"\s*:[^{]+\{(.*?)\}", source, re.S).group(1)
        body = re.sub(r"//[^\n]*", "", body)
        value = -1
        for declaration in body.split(","):
            declaration = declaration.strip()
            if not declaration:
                continue
            parts = declaration.split("=")
            name = parts[0].strip()
            value = int(parts[1].strip()) if len(parts) == 2 else value + 1
            exit_class = default_exit
            if prefix == "PARSE" and name in ("InternalNotAnAtom", "InternalNotAReaderToken"):
                exit_class = 70
            if prefix == "EXPAND" and name == "ExpansionDepthExceeded":
                exit_class = 2
            if prefix == "UNIFIED":
                if value < 200 or name in ("ExpansionDepthExceeded", "StackOverflow", "FrameOverflow", "HeapAllocationFailed", "InternTableFull"):
                    exit_class = 2
                if name in ("InternalError", "InvalidInstruction", "StackUnderflow"):
                    exit_class = 70
            code = f"{namespace}.{value if prefix == 'UNIFIED' else name}"
            rows.append(f"| `{name}` | [`{api}`](../{path}) | `{code}` | "
                        f"{'native message + related spans' if prefix == 'UNIFIED' else 'native/shared message + native span'}; location optional | {exit_class} |")
            fixtures.append(f"CST_{prefix}_KIND({name}, {exit_class})")
    return {
        ROOT / "docs/tooling_diagnostics.md": "\n".join(rows) + "\n",
        ROOT / "eta/qa/test/src/cst_diagnostic_kinds.inc": "\n".join(fixtures) + "\n",
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.write:
            path.write_text(content, encoding="utf-8", newline="\n")
        elif not path.is_file() or path.read_text(encoding="utf-8") != content:
            raise SystemExit(f"Stale diagnostic inventory: {path.relative_to(ROOT)}")
    print("Diagnostic inventory and per-kind fixtures match native enums")


if __name__ == "__main__":
    main()
